/** 한 시험지의 모든 페이지 URL 배열 (page 순). */
export function getSuneungPages(
  subject: Subject,
  variant: ExamVariant,
  year: number,
): string[] {
  return SUNEUNG_PAGES_RAW.filter(
    (e) => e.subject === subject && e.variant === variant && e.year === year,
  )
    .sort((a, b) => a.page - b.page)
    .map((e) => e.url);
}

/**
 * 한 시험지에서 특정 문제 번호가 있을 가능성이 높은 페이지 URL 들.
 * PDF 페이지에 문제 N 번이 정확히 어디 있는지는 OCR 없이는 알 수 없으므로,
 * 일단 전체 페이지를 반환 (Vision LLM 이 multimodal 입력으로 처리).
 *
 * 향후 OCR 으로 문제 번호 ↔ 페이지 매핑 정밀화 가능.
 */
export function getSuneungPagesForNumber(
  subject: Subject,
  variant: ExamVariant,
  year: number,
  _number: number,
): string[] {
  return getSuneungPages(subject, variant, year);
}
